// CIP-67 asset name labels and the asset classification rule spend types use.
//
// CIP-67 (cardano-foundation/CIPs at 4fa39658c9c0e95a13e2957a88afd353b48b5452,
// CIP-0067/README.md, "Specification"): an asset name that carries a label
// starts with four bytes
//   [ 0000 | 16 bits label_num | 8 bits checksum | 0000 ]
// whose checksum is CRC-8, polynomial 0x07, over the two label_num bytes, with
// the lookup table the CIP prints (beginning 0x00, 0x07, 0x0e). CIP-0067's
// registry.json at that commit holds 100, 222 and 500 (class NFT), 333 (FT)
// and 444 (RFT); CIP-68 ("Labels", "333 FT Standard", "444 RFT Standard")
// defines the first four, CIP-102 label 500. Open pull request 1207 would add
// 600 and 601; any label outside the five falls to the quantity rule, as do
// the private-use labels 0 to 15.
//
// The classification: a valid label 333 or 444 makes an asset fungible; 222,
// 100 and 500 are non-fungible unless more than one unit is held; otherwise
// more than one unit held makes an asset fungible. Labels are the first four
// bytes of the name; the name's size is always its full byte length.

