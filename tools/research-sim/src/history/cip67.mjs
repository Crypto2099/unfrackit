// CRC-8, polynomial 0x07, initial value 0, no reflection, no final XOR.
export function crc8(bytes) {
  let c = 0;
  for (const b of bytes) c = TABLE[c ^ b];
  return c;
}

// The label of an asset name (hex), or null when the name has fewer than four
// bytes, a non-zero bracket nibble, or a checksum that does not match.
export function cip67Label(nameHex) {
  const b = Buffer.from(nameHex, 'hex');
  if (b.length < 4) return null;
  if (b[0] >> 4 !== 0 || (b[3] & 15) !== 0) return null;
  const hi = ((b[0] & 15) << 4) | (b[1] >> 4);
  const lo = ((b[1] & 15) << 4) | (b[2] >> 4);
  const checksum = ((b[2] & 15) << 4) | (b[3] >> 4);
  if (crc8([hi, lo]) !== checksum) return null;
  return (hi << 8) | lo;
}

// The four label bytes for a label number (CIP-67, "Construct a label").
export function cip67Prefix(label) {
  const hi = (label >> 8) & 0xff;
  const lo = label & 0xff;
  const c = crc8([hi, lo]);
  const word = (BigInt(label) << 12n) | (BigInt(c) << 4n);
  return word.toString(16).padStart(8, '0');
}

export const FUNGIBLE_LABELS = new Set([333, 444]);

// The rule for an asset held (or moved) as `units` in total.
export function isFungible(nameHex, units) {
  const label = cip67Label(nameHex);
  if (label !== null && FUNGIBLE_LABELS.has(label)) return true;
  return BigInt(units) > 1n;
}
